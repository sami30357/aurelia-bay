// Aurelia Bay — deterministic random numbers (mulberry32).
// One job: every seeded roll in the game comes from here, so a seed
// always builds the same city, the same traffic and the same peds.

export function mulberry32(seed) {
  let a = seed >>> 0;
  return function random() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function pick(random, list) {
  return list[Math.floor(random() * list.length)];
}

export function range(random, min, max) {
  return min + random() * (max - min);
}

export function intRange(random, min, max) {
  return min + Math.floor(random() * (max - min + 1));
}

export function chance(random, probability) {
  return random() < probability;
}

// Fisher-Yates shuffle, in place, driven by the seeded random.
export function shuffle(random, list) {
  for (let i = list.length - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    const tmp = list[i];
    list[i] = list[j];
    list[j] = tmp;
  }
  return list;
}
